package e3.chapter3;

/**
 * The types of poker hands, declared from the weakest to the strongest, so that
 * the natural (ordinal) order of the constants is the order of strength.
 */
public enum PokerHandType {
	HIGH_CARD, ONE_PAIR, TWO_PAIR, THREE_OF_A_KIND, STRAIGHT, FLUSH, FULL_HOUSE, FOUR_OF_A_KIND, STRAIGHT_FLUSH
}